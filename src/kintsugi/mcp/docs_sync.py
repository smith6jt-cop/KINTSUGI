"""Generate and verify the MCP tool reference embedded in the documentation.

The tool table in ``docs/mcp.md``, ``docs/cli.md`` and ``README.md`` (and the
name list in ``CLAUDE.md``) is rendered from :data:`kintsugi.mcp.tool_specs.TOOL_SPECS`
and spliced between marker comments::

    <!-- mcp-tools:table:begin -->
    ...generated...
    <!-- mcp-tools:table:end -->

``kintsugi mcp tools --write FILE...`` regenerates the blocks and
``kintsugi mcp tools --check FILE...`` fails when a block is stale, which CI and
the eval harness run so the documented tool surface can never drift from the
registry again. Only the registry and the standard library are imported, so this
works without the optional ``claude`` extra.
"""

from __future__ import annotations

import re
from pathlib import Path

from kintsugi.mcp.tool_specs import TOOL_SPECS

CATEGORY_LABELS: dict[str, str] = {
    "signal_isolation": "Signal isolation",
    "quality_assessment": "Quality assessment",
    "visualization": "Visualization",
    "workflow": "Workflow",
    "learning": "Parameter learning",
}

BLOCKS = ("table", "list")


class DocsSyncError(ValueError):
    """Raised when a marker block is missing or malformed."""


def _hint(spec: dict, key: str) -> str:
    return "yes" if spec["annotations"].get(key) else "no"


def render_tool_table() -> str:
    """Markdown table of every registered tool (name, title, category, hints, description)."""
    lines = [
        "| Tool | Title | Category | Read-only | Writes files | Description |",
        "|------|-------|----------|:---------:|:------------:|-------------|",
    ]
    for spec in TOOL_SPECS:
        lines.append(
            "| `{name}` | {title} | {category} | {ro} | {destr} | {desc} |".format(
                name=spec["name"],
                title=spec["title"],
                category=CATEGORY_LABELS.get(spec["module"], spec["module"]),
                ro=_hint(spec, "readOnlyHint"),
                destr=_hint(spec, "destructiveHint"),
                desc=spec["description"].replace("|", "\\|"),
            )
        )
    lines.append("")
    lines.append(
        f"{len(TOOL_SPECS)} tools. Generated by `kintsugi mcp tools --write`; do not edit by hand."
    )
    return "\n".join(lines)


def render_tool_list() -> str:
    """Compact bullet list grouped by category (used where a table is too heavy).

    The registry is not sorted by module, so categories are collected in
    first-seen order and each is emitted once.
    """
    by_module: dict[str, list[str]] = {}
    for spec in TOOL_SPECS:
        by_module.setdefault(spec["module"], []).append(f"`{spec['name']}`")
    lines = [
        f"- **{CATEGORY_LABELS.get(module, module)}:** " + ", ".join(names)
        for module, names in by_module.items()
    ]
    lines.append("")
    lines.append(
        f"{len(TOOL_SPECS)} tools. Generated by `kintsugi mcp tools --write`; do not edit by hand."
    )
    return "\n".join(lines)


def render_block(kind: str) -> str:
    if kind == "table":
        return render_tool_table()
    if kind == "list":
        return render_tool_list()
    raise DocsSyncError(f"unknown block kind {kind!r}; expected one of {BLOCKS}")


def _pattern(kind: str) -> re.Pattern[str]:
    return re.compile(
        rf"(<!-- mcp-tools:{kind}:begin -->\n)(.*?)(\n?<!-- mcp-tools:{kind}:end -->)",
        re.DOTALL,
    )


def find_blocks(text: str) -> list[str]:
    """Return the block kinds whose markers appear in ``text``."""
    return [kind for kind in BLOCKS if _pattern(kind).search(text)]


def splice_block(text: str, kind: str, body: str | None = None) -> str:
    """Replace the content between the ``kind`` markers with ``body`` (rendered if None)."""
    body = render_block(kind) if body is None else body
    pattern = _pattern(kind)
    if not pattern.search(text):
        raise DocsSyncError(f"no <!-- mcp-tools:{kind}:begin/end --> markers found")
    return pattern.sub(lambda m: f"{m.group(1)}{body}\n{m.group(3).lstrip()}", text, count=1)


def sync_file(path: str | Path, *, write: bool) -> dict[str, bool]:
    """Regenerate (``write=True``) or check every marker block in ``path``.

    Returns ``{kind: up_to_date}`` for each block found. Raises
    :class:`DocsSyncError` when the file has no blocks at all.
    """
    path = Path(path)
    original = path.read_text()
    kinds = find_blocks(original)
    if not kinds:
        raise DocsSyncError(f"{path}: no mcp-tools marker blocks found")
    updated = original
    for kind in kinds:
        updated = splice_block(updated, kind)
    status = {
        kind: _pattern(kind).search(original).group(2).strip() == render_block(kind).strip()
        for kind in kinds
    }
    if write and updated != original:
        path.write_text(updated)
    return status


def check_files(paths: list[str | Path]) -> list[str]:
    """Return human-readable problems for every stale block across ``paths``."""
    problems: list[str] = []
    for path in paths:
        try:
            status = sync_file(path, write=False)
        except (DocsSyncError, FileNotFoundError) as exc:
            problems.append(str(exc))
            continue
        problems.extend(
            f"{path}: mcp-tools:{kind} block is stale" for kind, ok in status.items() if not ok
        )
    return problems
