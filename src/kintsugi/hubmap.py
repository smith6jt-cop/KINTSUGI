@dataclass
class CycleDir:
    cycle: int
    region: int
    path: Path
    n_tiles: int


def _cycle_dirs(directory: Path) -> list[CycleDir]:
    found = []
    for child in sorted(directory.iterdir()) if directory.is_dir() else []:
        match = CYCLE_DIR_RE.match(child.name)
        if not match or not child.is_dir():
            continue
        tiles = sum(1 for f in child.iterdir() if TILE_RE.match(f.name))
        found.append(
            CycleDir(
                cycle=int(match["cycle"]),
                region=int(match["region"] or 1),
                path=child,
                n_tiles=tiles,
            )
        )
    return found


def find_source_dir(download_dir: str | os.PathLike[str], max_depth: int = 4) -> Path:
    """The directory under ``download_dir`` that holds the cycle directories.

    Globus downloads nest the data (``<id>/``, ``src_<name>/``, ``raw/`` ...), so
    the tree is searched breadth-first up to ``max_depth`` levels.
    """
    root = Path(download_dir).resolve()
    if not root.is_dir():
        raise HubmapError(f"Download directory not found: {root}")
    level = [root]
    for _ in range(max_depth + 1):
        for directory in level:
            if any(c.n_tiles for c in _cycle_dirs(directory)):
                return directory
        level = [c for d in level for c in sorted(d.iterdir()) if c.is_dir()]
        if not level:
            break
    raise HubmapError(
        f"No CODEX cycle directories (e.g. Cyc1_reg1/ with 1_00001_Z001_CH1.tif tiles) "
        f"found under {root}"
    )


def _find_file(source: Path, names: tuple[str, ...]) -> Path | None:
    for directory in (source, *source.parents[:2]):
        for name in names:
            candidate = directory / name
            if candidate.is_file():
                return candidate
    return None


