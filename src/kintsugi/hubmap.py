@dataclass
class StageReport:
    project: Path
    source: Path
    region: int
    cycles: dict[int, str]
    tiles_per_cycle: dict[int, int]
    experiment_json: Path | None
    channel_names: Path | None
    provenance: Path
    warnings: list[str] = field(default_factory=list)


def stage_dataset(
    download_dir: str | os.PathLike[str],
    project_dir: str | os.PathLike[str],
    *,
    region: int = 1,
    hubmap_id: str | None = None,
    dataset: DatasetInfo | None = None,
    copy: bool = False,
    force: bool = False,
) -> StageReport:
    """Stage a downloaded raw CODEX dataset into an initialized KINTSUGI project.

    Parameters
    ----------
    download_dir
        The downloaded dataset (any nesting; see :func:`find_source_dir`).
    project_dir
        A project created with ``kintsugi init`` (has ``kintsugi_project.json``).
    region
        CODEX region to stage (``_reg001``); datasets usually have one.
    hubmap_id, dataset
        Recorded in ``meta/hubmap_provenance.json``; ``dataset`` (from
        :func:`fetch_dataset`) adds title, DOI and acquisition metadata.
    copy
        Copy the cycle directories instead of symlinking them.
    force
        Replace existing ``data/raw/cyc###`` entries and metadata files.
    """
    from kintsugi.project import ExperimentConfig, KintsugiProject

    project_root = Path(project_dir).resolve()
    if not (project_root / "kintsugi_project.json").is_file():
        raise HubmapError(
            f"{project_root} is not a KINTSUGI project; create it first with "
            f"'kintsugi init {project_root}'."
        )
    project = KintsugiProject.load(project_root)
    source = find_source_dir(download_dir)
    cycles = [c for c in _cycle_dirs(source) if c.region == region and c.n_tiles]
    if not cycles:
        raise HubmapError(f"No cycle directories for region {region} in {source}")
    duplicates = sorted({c.cycle for c in cycles if sum(d.cycle == c.cycle for d in cycles) > 1})
    if duplicates:
        raise HubmapError(f"Several directories for cycle(s) {duplicates} in {source}")

    warnings: list[str] = []
    raw = project.paths.raw
    raw.mkdir(parents=True, exist_ok=True)
    staged: dict[int, str] = {}
    for cyc in sorted(cycles, key=lambda c: c.cycle):
        target = raw / f"cyc{cyc.cycle:03d}"
        if target.exists() or target.is_symlink():
            if not force:
                raise HubmapError(f"{target} already exists; pass force=True to replace it.")
            if target.is_symlink() or target.is_file():
                target.unlink()
            else:
                shutil.rmtree(target)
        if copy:
            shutil.copytree(cyc.path, target)
        else:
            target.symlink_to(cyc.path, target_is_directory=True)
        staged[cyc.cycle] = str(cyc.path)
    tiles = {c.cycle: c.n_tiles for c in cycles}
    if len(set(tiles.values())) > 1:
        warnings.append(f"Cycles have different tile counts: {tiles}")
    numbers = sorted(staged)
    if numbers != list(range(numbers[0], numbers[0] + len(numbers))):
        warnings.append(f"Cycle numbers are not contiguous: {numbers}")

    # experiment.json -> meta/experiment.json (KINTSUGI field names)
    exp_src = _find_file(source, EXPERIMENT_NAMES)
    exp_dst: Path | None = None
    if exp_src is None:
        warnings.append("No experiment.json found; meta/experiment.json left unchanged.")
    else:
        data = json.loads(exp_src.read_text())
        config = ExperimentConfig.from_dict(dict(data))
        if "numCycles" not in data and "n_cycles" not in data:
            config.n_cycles = len(staged)
        exp_dst = project.save_experiment_config(config)
        (project.paths.meta / "experiment.source.json").write_text(json.dumps(data, indent=2))

    # channelnames.txt -> meta/CHANNELNAMES.txt
    names_src = _find_file(source, CHANNELNAME_NAMES)
    names_dst: Path | None = None
    if names_src is None:
        warnings.append("No channelnames.txt found; create meta/CHANNELNAMES.txt by hand.")
    else:
        names_dst = project.paths.meta / "CHANNELNAMES.txt"
        if names_dst.exists() and not force:
            warnings.append(f"{names_dst} exists; kept (force=True replaces it).")
        else:
            shutil.copyfile(names_src, names_dst)

    now = datetime.now(timezone.utc).isoformat(timespec="seconds")
    if dataset is None and hubmap_id:
        dataset = DatasetInfo(hubmap_id=validate_hubmap_id(hubmap_id), uuid="")
    provenance = {
        "staged_at": now,
        "source_directory": str(source),
        "region": region,
        "cycles": {f"cyc{k:03d}": v for k, v in staged.items()},
        "tiles_per_cycle": {f"cyc{k:03d}": v for k, v in tiles.items()},
        "mode": "copy" if copy else "symlink",
        "dataset": asdict(dataset) if dataset else None,
        "portal_url": dataset.portal_url if dataset and dataset.uuid else None,
        "citation": {
            "acknowledgement": HUBMAP_ACKNOWLEDGEMENT,
            "consortium": HUBMAP_CONSORTIUM_CITATION,
            "dataset_doi": dataset.doi_url if dataset else None,
            "license": "HuBMAP external data sharing policy (open access imaging data)",
        },
    }
    provenance_path = project.paths.meta / "hubmap_provenance.json"
    provenance_path.write_text(json.dumps(provenance, indent=2, default=str))
    label = dataset.hubmap_id if dataset else source.name
    (raw / ".staged").write_text(f"staged from HuBMAP {label} at {now}\nsource: {source}\n")

    return StageReport(
        project=project_root,
        source=source,
        region=region,
        cycles=staged,
        tiles_per_cycle=tiles,
        experiment_json=exp_dst,
        channel_names=names_dst if names_src else None,
        provenance=provenance_path,
        warnings=warnings,
    )
