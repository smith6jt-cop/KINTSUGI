"""Fetch and stage public HuBMAP CODEX datasets as KINTSUGI projects.

HuBMAP (https://hubmapconsortium.org) publishes raw CODEX imaging openly; the
files are served over Globus and downloaded with the HuBMAP command-line
transfer tool (``pip install hubmap-clt``)::

    kintsugi hubmap manifest HBM283.GNGR.785 -o manifest.txt   # this module
    hubmap-clt login
    hubmap-clt transfer manifest.txt -d /path/to/downloads    # Globus transfer
    kintsugi init /path/to/project --name HBM283_LN
    kintsugi hubmap stage /path/to/downloads/HBM283.GNGR.785 /path/to/project \\
        --hubmap-id HBM283.GNGR.785

A raw CODEX dataset holds one directory per imaging cycle (``Cyc1_reg1``,
``cyc001_reg001_<date>``, ...) with tiles named
``{region}_{tile:05d}_Z{z:03d}_CH{channel}.tif`` — the layout KINTSUGI's
stitching already reads — plus ``experiment.json`` (CODEX instrument fields,
translated by :meth:`kintsugi.project.ExperimentConfig.from_dict`) and
``channelnames.txt``. :func:`stage_dataset` links the cycle directories into
``data/raw/cyc###`` without copying, writes ``meta/experiment.json`` and
``meta/CHANNELNAMES.txt``, marks the raw data staged and records the provenance
and citation HuBMAP's data-use policy asks for in ``meta/hubmap_provenance.json``.

Only the standard library is used for HTTP; the HuBMAP APIs used here are
public and need no token for published, public datasets.
"""

from __future__ import annotations

import json
import os
import re
import shutil
import urllib.parse
import urllib.request
from collections.abc import Callable
from dataclasses import asdict, dataclass, field
from datetime import datetime, timezone
from pathlib import Path
from typing import Any

ENTITY_API = "https://entity.api.hubmapconsortium.org/entities/"
SEARCH_API = "https://search.api.hubmapconsortium.org/v3/param-search/datasets"
PORTAL_URL = "https://portal.hubmapconsortium.org/browse/dataset/"

HUBMAP_ID_RE = re.compile(r"^HBM\d{3}\.[A-Z]{4}\.\d{3}$")

#: Cycle directory names seen in CODEX/HuBMAP raw data: ``Cyc1_reg1``,
#: ``cyc001_reg001_211118``, ``cyc01``, ``Cycle3``.
CYCLE_DIR_RE = re.compile(r"^cyc(?:le)?_?0*(?P<cycle>\d+)(?:_reg0*(?P<region>\d+))?(?:_.*)?$", re.I)
TILE_RE = re.compile(r"^(?P<region>\d+)_(?P<tile>\d+)_Z(?P<z>\d+)_CH(?P<ch>\d+)\.tiff?$", re.I)

EXPERIMENT_NAMES = ("experiment.json", "Experiment.json")
CHANNELNAME_NAMES = ("channelnames.txt", "channelNames.txt", "CHANNELNAMES.txt")

HUBMAP_ACKNOWLEDGEMENT = (
    "The results here are in whole or part based upon data generated by the HuBMAP "
    "Program: https://hubmapconsortium.org"
)
HUBMAP_CONSORTIUM_CITATION = (
    "HuBMAP Consortium. The human body at cellular resolution: the NIH Human "
    "Biomolecular Atlas Program. Nature 574, 187-192 (2019). "
    "https://doi.org/10.1038/s41586-019-1629-x"
)

#: ``fetch(url, as_json=True)`` -> parsed JSON or text; injectable for tests.
Fetcher = Callable[..., Any]


class HubmapError(RuntimeError):
    """A HuBMAP lookup failed or a download directory cannot be staged."""


# ---------------------------------------------------------------------------
# HuBMAP API
# ---------------------------------------------------------------------------


def _fetch(url: str, *, as_json: bool = True, timeout: float = 60.0) -> Any:
    request = urllib.request.Request(url, headers={"User-Agent": "kintsugi-hubmap"})
    with urllib.request.urlopen(request, timeout=timeout) as response:  # noqa: S310 (fixed https hosts)
        body = response.read().decode("utf-8")
    return json.loads(body) if as_json else body


def validate_hubmap_id(hubmap_id: str) -> str:
    """Return ``hubmap_id`` upper-cased, or raise :class:`HubmapError` if malformed."""
    candidate = hubmap_id.strip().upper()
    if not HUBMAP_ID_RE.match(candidate):
        raise HubmapError(f"Not a HuBMAP ID (expected e.g. HBM283.GNGR.785): {hubmap_id!r}")
    return candidate


@dataclass
class DatasetInfo:
    """Public metadata of a HuBMAP dataset, as recorded in the project provenance."""

    hubmap_id: str
    uuid: str
    title: str = ""
    dataset_type: str = ""
    status: str = ""
    data_access_level: str = ""
    doi_url: str | None = None
    group_name: str = ""
    contains_human_genetic_sequences: bool | None = None
    acquisition: dict[str, Any] = field(default_factory=dict)

    @property
    def portal_url(self) -> str:
        return f"{PORTAL_URL}{self.uuid}"

    @classmethod
    def from_entity(cls, entity: dict[str, Any]) -> DatasetInfo:
        metadata = entity.get("metadata") or {}
        if "metadata" in metadata and isinstance(metadata["metadata"], dict):
            metadata = metadata["metadata"]
        keys = (
            "acquisition_instrument_vendor",
            "acquisition_instrument_model",
            "number_of_biomarker_imaging_rounds",
            "number_of_channels",
            "number_of_antibodies",
            "resolution_x_value",
            "resolution_x_unit",
            "resolution_z_value",
            "resolution_z_unit",
            "preparation_protocol_doi",
        )
        return cls(
            hubmap_id=entity.get("hubmap_id", ""),
            uuid=entity.get("uuid", ""),
            title=entity.get("title", "") or "",
            dataset_type=entity.get("dataset_type", "") or "",
            status=entity.get("status", "") or "",
            data_access_level=entity.get("data_access_level", "") or "",
            doi_url=entity.get("doi_url"),
            group_name=entity.get("group_name", "") or "",
            contains_human_genetic_sequences=entity.get("contains_human_genetic_sequences"),
            acquisition={k: metadata[k] for k in keys if metadata.get(k) not in (None, "")},
        )


def fetch_dataset(hubmap_id: str, fetch: Fetcher | None = None) -> DatasetInfo:
    """Look up a dataset in the HuBMAP entity API and check it is public."""
    hubmap_id = validate_hubmap_id(hubmap_id)
    fetch = fetch or _fetch
    try:
        entity = fetch(ENTITY_API + urllib.parse.quote(hubmap_id))
    except OSError as exc:
        raise HubmapError(f"HuBMAP entity API lookup of {hubmap_id} failed: {exc}") from exc
    if not isinstance(entity, dict) or not entity.get("uuid"):
        raise HubmapError(f"HuBMAP entity API returned no dataset for {hubmap_id}")
    info = DatasetInfo.from_entity(entity)
    if info.data_access_level and info.data_access_level != "public":
        raise HubmapError(
            f"{hubmap_id} is {info.data_access_level!r}, not public; it needs approved access."
        )
    return info


def manifest_text(hubmap_id: str, fetch: Fetcher | None = None) -> str:
    """The ``hubmap-clt`` manifest that downloads the whole dataset.

    Asks the search API to produce it (``produce-clt-manifest=true``); the
    format is one ``<HuBMAP ID> <path>`` line per entry, ``/`` meaning all files.
    """
    hubmap_id = validate_hubmap_id(hubmap_id)
    fetch = fetch or _fetch
    query = urllib.parse.urlencode({"hubmap_id": hubmap_id, "produce-clt-manifest": "true"})
    try:
        text = str(fetch(f"{SEARCH_API}?{query}", as_json=False)).strip()
    except OSError:
        text = ""
    if not text.startswith(hubmap_id):
        text = f"{hubmap_id} /"
    return text + "\n"


